import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {ensureCiRetryTable,scheduleCiRetry,claimDueCiRetry,markCiRetryOutcome,resumeCiObservation} from '../src/jobs/ci-retry-store.mjs';
const sha='a'.repeat(40);
test('CI retry is durable, bounded and claimed once',()=>{
 const db=new DatabaseSync(':memory:');ensureCiRetryTable(db);
 const first=scheduleCiRetry(db,{runId:42,headSha:sha,reason:'network',now:100000});
 assert.equal(first.delayMs,10000);assert.equal(first.nextRetryCount,1);
 assert.equal(scheduleCiRetry(db,{runId:42,headSha:sha,reason:'network',now:100001}).retry,false);
 assert.equal(claimDueCiRetry(db,{runId:42,now:109999}),false);
 assert.equal(claimDueCiRetry(db,{runId:42,now:110000}),true);
 assert.equal(claimDueCiRetry(db,{runId:42,now:110000}),false);
 assert.equal(markCiRetryOutcome(db,{runId:42,acknowledged:true}),true);
 assert.equal(resumeCiObservation(db,{runId:42,headSha:sha,confirmedCompleted:true}),true);
 const second=scheduleCiRetry(db,{runId:42,headSha:sha,reason:'runner_lost',now:200000});
 assert.equal(second.delayMs,30000);
 assert.equal(claimDueCiRetry(db,{runId:42,now:230000}),true);
 assert.equal(markCiRetryOutcome(db,{runId:42,acknowledged:true}),true);
 assert.equal(resumeCiObservation(db,{runId:42,headSha:sha,confirmedCompleted:true}),true);
 const third=scheduleCiRetry(db,{runId:42,headSha:sha,reason:'rate_limit',now:300000});
 assert.equal(third.delayMs,90000);
 assert.equal(claimDueCiRetry(db,{runId:42,now:390000}),true);
 assert.equal(markCiRetryOutcome(db,{runId:42,acknowledged:true}),true);
 assert.equal(resumeCiObservation(db,{runId:42,headSha:sha,confirmedCompleted:true}),true);
 assert.equal(scheduleCiRetry(db,{runId:42,headSha:sha,reason:'network'}).state,'blocked');
 assert.equal(db.prepare('SELECT retry_count FROM ci_retry_runs WHERE run_id=42').get().retry_count,3);
 db.close();
});
test('deterministic failures and unknown dispatch outcome do not retry',()=>{
 const db=new DatabaseSync(':memory:');
 assert.equal(scheduleCiRetry(db,{runId:1,headSha:sha,reason:'test_failure'}).state,'blocked');
 assert.equal(scheduleCiRetry(db,{runId:2,headSha:sha,reason:'network',now:0}).retry,true);
 assert.equal(claimDueCiRetry(db,{runId:2,now:10000}),true);
 assert.equal(markCiRetryOutcome(db,{runId:2,acknowledged:false}),true);
 assert.equal(resumeCiObservation(db,{runId:2,headSha:sha,confirmedCompleted:true}),false);
 assert.throws(()=>scheduleCiRetry(db,{runId:2,headSha:'b'.repeat(40),reason:'network'}),/mismatch/);
 db.close();
});
